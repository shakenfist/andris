#!/usr/bin/env python3
"""Generate andris's evdev-code-to-qnum table for the qemu platform.

Andris injects keys as Linux evdev codes. qemu's D-Bus display takes them as qnums: the PC's AT set 1 scan code,
with a two-byte 0xe0 code folded into one byte by setting its top bit. This script makes the table from
keycodemapdb's data/keymaps.csv, which gives each Linux key its AT set 1 code, and folds each code the way
keycodemapdb's own keymap-gen does: 0xe0XX becomes 0x80 | XX, and the two Hanja and Hangeul keys (0xf1 and 0xf2,
which have no prefix) lose their top bit.

It writes andris/src/platform/qemu/qnums.rs. keycodemapdb is dual licensed, GPL-2.0-or-later or BSD-3-Clause, and
its generated tables may be used under either; andris takes them under BSD-3-Clause, whose notice the table
carries, read from LICENSE.BSD beside the data directory.

Usage: scripts/gen-qemu-qnums.py --keycodemapdb DIR --version REVISION

DIR is a keycodemapdb checkout (https://gitlab.com/keycodemap/keycodemapdb), and REVISION the commit it is at.
Run it from anywhere; the output path is relative to the repository root.
"""

import argparse
import csv
import hashlib
import os


REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_PATH = os.path.join(REPO_ROOT, 'andris', 'src', 'platform', 'qemu', 'qnums.rs')

# Columns of keymaps.csv.
LINUX_NAME = 0
LINUX_CODE = 1
AT_SET1 = 4

# The Hanja and Hangeul keys, whose set 1 codes have no 0xe0 prefix but keep a qnum below 0x80.
HANJA_HANGEUL = (0xf1, 0xf2)


def qnum(at1):
    """The qnum of AT set 1 code `at1`, as keymap-gen computes it."""
    if at1 in HANJA_HANGEUL:
        return at1 & 0x7f
    if at1 > 0x7f:
        if at1 & ~0x7f != 0xe000:
            raise ValueError('set 1 code %#x is neither one byte nor 0xe0-prefixed' % at1)
        return 0x80 | (at1 & 0x7f)
    return at1


def read_table(path):
    """Each Linux key with a set 1 code, as a sorted list of (evdev code, qnum, Linux name)."""
    table = {}
    with open(path, newline='') as f:
        rows = csv.reader(f)
        next(rows)
        for row in rows:
            if not row[LINUX_CODE] or not row[AT_SET1]:
                continue
            code = int(row[LINUX_CODE], 0)
            value = qnum(int(row[AT_SET1], 0))
            if value:
                table[code] = (value, row[LINUX_NAME] or 'no Linux name')
    return sorted((code, value, name) for code, (value, name) in table.items())


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--keycodemapdb', required=True, help='a keycodemapdb checkout')
    parser.add_argument('--version', required=True, help='the keycodemapdb commit to record')
    args = parser.parse_args()

    csv_path = os.path.join(args.keycodemapdb, 'data', 'keymaps.csv')
    with open(csv_path, 'rb') as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    with open(os.path.join(args.keycodemapdb, 'LICENSE.BSD')) as f:
        licence = f.read().rstrip('\n').split('\n')
    table = read_table(csv_path)

    lines = [
        '//! The qnum of each Linux evdev key code, generated by',
        '//! `scripts/gen-qemu-qnums.py`. Do not edit it by hand; run the script.',
        '//!',
        '//! Source: keycodemapdb\'s `data/keymaps.csv` at %s' % args.version,
        '//! (sha256 %s),' % digest,
        '//! <https://gitlab.com/keycodemap/keycodemapdb>. Its generated tables',
        '//! may be used under GPL-2.0-or-later or BSD-3-Clause; andris takes',
        '//! this one under BSD-3-Clause, whose notice follows.',
        '//!',
    ]
    lines.append('//! ```text')
    lines += [('//! ' + line).rstrip() for line in licence]
    lines.append('//! ```')
    lines += [
        '',
        '/// Evdev code and qnum, sorted by evdev code. Keys with no qnum are left out.',
        '#[rustfmt::skip]',
        'pub(super) const QNUMS: &[(u16, u16)] = &[',
    ]
    for code, value, name in table:
        lines.append('    (%d, %#04x), // %s' % (code, value, name))
    lines.append('];')
    with open(OUT_PATH, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %d qnums to %s' % (len(table), OUT_PATH))


if __name__ == '__main__':
    main()
